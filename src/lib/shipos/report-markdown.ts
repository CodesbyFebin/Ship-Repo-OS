import type { AuditJobResponse, AuditRisk, RepoAudit } from "./audit-types";
import { RISK_SEVERITY_ORDER } from "./audit-types";

const SEVERITY_LABEL: Record<AuditRisk["severity"], string> = {
  critical: "CRITICAL",
  high: "HIGH",
  medium: "MEDIUM",
  low: "LOW",
};

/** Full markdown audit report — header, categories, losses, risks, roadmap, fixes. */
export function buildReportMarkdown(job: AuditJobResponse): string {
  const audit = job.audit;
  if (!audit) return "";

  const date = new Date(job.createdAt).toUTCString();
  const lines: string[] = [];

  // Header
  lines.push(`# Audit Report — ${job.owner}/${job.repo}`, ``);
  lines.push(
    `**Score: ${audit.score}/100** · Grade **${audit.grade}** (${audit.tier}) · ${audit.percentile} · strictness: \`${audit.strictness}\``,
    ``,
    `**Audited:** ${date} · **Engine:** ShipOS Full Repo Auditor — 50 deterministic checks, 5 weighted categories, zero LLM guessing.`,
    ``
  );
  if (job.repoMeta?.description) lines.push(`> ${job.repoMeta.description}`, ``);

  // Category table
  lines.push(`## Score breakdown`, ``, `| Category | Score | Max | % |`, `| --- | --- | --- | --- |`);
  for (const c of audit.categories) {
    const pct = Math.round((c.score / c.max) * 100);
    lines.push(`| ${c.name} | ${c.score} | ${c.max} | ${pct}% |`);
  }
  lines.push(``, `**Checks passed:** ${audit.stats.checksPassed}/${audit.stats.checksTotal} · **Points at stake:** ${audit.stats.pointsAtStake}`, ``);

  // Points lost
  const lost = audit.categories
    .flatMap((c) => c.checks.filter((ch) => !ch.pass && !ch.na).map((ch) => ({ ...ch, category: c.name })))
    .sort((a, b) => b.weight - a.weight);
  if (lost.length) {
    lines.push(`## Points lost — exactly where they went`, ``, `| Points | Check | Category | Evidence |`, `| --- | --- | --- | --- |`);
    for (const ch of lost) lines.push(`| -${ch.weight} | ${ch.label} | ${ch.category} | ${ch.detail.replace(/\|/g, "\\|")} |`);
    lines.push(``);
  }

  // Risks by severity
  if (audit.risks.length) {
    const risks = [...audit.risks].sort((a, b) => RISK_SEVERITY_ORDER[a.severity] - RISK_SEVERITY_ORDER[b.severity]);
    lines.push(`## Risk assessment`, ``);
    for (const r of risks) lines.push(`- **[${SEVERITY_LABEL[r.severity]}]** ${r.title} — ${r.detail} _(check: ${r.checkId})_`);
    lines.push(``);
  }

  // Roadmap with cumulative scores
  lines.push(`## Roadmap to 100/100`, ``, `| # | Fix | Points | Effort | Score after |`, `| --- | --- | --- | --- | --- |`);
  for (const step of audit.roadmap) {
    lines.push(`| ${step.rank} | ${step.title} | +${step.points} | ${step.effort} | ${step.cumulative}/100 |`);
  }
  lines.push(``);

  // Per-fix sections with full code
  lines.push(`## Fixes — full copy-paste code`, ``);
  for (const f of audit.fixes) {
    lines.push(`### ${f.rank}. ${f.title} (+${f.points} pts · ${f.priority} · ${f.effort})`, ``, f.why, ``);
    lines.push(`Resolves ${f.checkIds.length} check(s): ${f.checkIds.map((id) => `\`${id}\``).join(", ")}`, ``);
    if (f.docsUrl) lines.push(`Official guide: ${f.docsUrl}`, ``);
    for (const file of f.files) {
      lines.push(`**File: \`${file.path}\`**`, ``, "```" + file.language, file.content, "```", ``);
    }
    if (f.manualSteps?.length) {
      lines.push(`**Manual steps:**`, ``, ...f.manualSteps.map((s, i) => `${i + 1}. ${s}`), ``);
    }
  }

  lines.push(`---`, ``, `Generated by ShipOS Full Repo Auditor — every missing point gets a ranked fix with full code.`, ``);
  return lines.join("\n");
}

/** Short shareable summary (3-6 lines) for social/copy. */
export function buildSummaryText(job: AuditJobResponse): string {
  const audit = job.audit;
  if (!audit) return "";
  const top = audit.fixes.slice(0, 3);
  const lines: string[] = [];
  lines.push(
    `${job.owner}/${job.repo} scored ${audit.score}/100 on a 50-check repo audit — Grade ${audit.grade}, ${audit.percentile}.`
  );
  if (top.length) {
    lines.push(
      `Top fixes: ${top.map((f) => `${f.title} (+${f.points} pts)`).join(" · ")}.`
    );
  }
  lines.push(
    `Full ranked roadmap to 100/100 with copy-paste code — audited by ShipOS.`
  );
  return lines.join("\n");
}
